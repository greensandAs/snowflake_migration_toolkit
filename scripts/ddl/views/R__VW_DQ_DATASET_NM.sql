USE DATABASE {{ snowflake_database }};

USE SCHEMA {{ snowflake_schema }};

CREATE OR REPLACE VIEW VW_DQ_DATASET_NM (
    DATASET_ID,
    PROJECT_ID,
    DATASET_NAME,
    PROJECT_NAME,
    DATABASE_NAME,
    SCHEMA_NAME,
    TABLE_NAME,
    CUSTOM_SQL
) AS
SELECT
    DATASET_ID,
    PROJECT_ID,
    UPPER(DATASET_NAME) AS DATASET_NAME,
    UPPER(PROJECT_NAME) PROJECT_NAME,
    UPPER(DATABASE_NAME) DATABASE_NAME,
    UPPER(SCHEMA_NAME) SCHEMA_NAME,
    UPPER(TABLE_NAME) TABLE_NAME,
    UPPER(CUSTOM_SQL) CUSTOM_SQL
FROM DQ_DATASET;
